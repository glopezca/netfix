// Generates src/ui/shots-data.ts (the help screenshots as data URIs) from assets/docs/*.webp (captured by scripts/shots.mjs).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets/docs');
const entries = readdirSync(dir).filter((f) => f.endsWith('.webp')).sort()
  .map((f) => `  '${f.slice(0, -5)}': 'data:image/webp;base64,${readFileSync(join(dir, f)).toString('base64')}',`);

writeFileSync(join(root, 'src/ui/shots-data.ts'), `/** Generated by scripts/gen-shots.mjs from assets/docs/ — do not edit. Keys: «<shot id>.<es|en>». */
export const SHOTS: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`);
