// Generates src/docs/about-data.ts (the «Acerca de» tab) from package.json and LICENSE.md.
// Usage: node scripts/gen-about.mjs [--stdout]
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const licenseMarkdown = readFileSync(join(root, 'LICENSE.md'), 'utf8');
const repoUrl = String(pkg.repository?.url ?? pkg.repository ?? '').replace(/^git\+/, '').replace(/\.git$/, '');

const data = {
  name: pkg.name,
  version: pkg.version,
  description: pkg.description,
  license: pkg.license,
  repository: repoUrl,
  licenseMarkdown,
};

const source = `/** Generated by scripts/gen-about.mjs from package.json and LICENSE.md — do not edit (npm run about). */
export interface AboutData {
  readonly name: string;
  readonly version: string;
  readonly description: string;
  readonly license: string;
  readonly repository: string;
  readonly licenseMarkdown: string;
}

export const ABOUT: AboutData = ${JSON.stringify(data, null, 2)};
`;

if (process.argv.includes('--stdout')) process.stdout.write(source);
else writeFileSync(join(root, 'src/docs/about-data.ts'), source);
