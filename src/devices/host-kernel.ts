/**
 * The Linux kernel side of a host: sysctl parameters, netfilter (nftables + conntrack) and the kernel
 * log (dmesg). The IP stack calls the hooks with the NIC's port name; netfilter sees Linux names.
 */
import type { IpPacket, UnreachableCode } from '../net/packets.ts';
import { LINUX_TTL, icmpQuote } from '../net/packets.ts';
import { Netfilter } from '../net/netfilter.ts';
import { Sysctl } from '../net/sysctl.ts';
import { LOOPBACK } from '../net/ipstack.ts';

const MAX_KERNEL_LOG = 200;

export interface KernelHost {
  readonly clock: { now(): number };
  runtimeName(): string;
  setTransientName(name: string | undefined): void;
  /** Linux name (eth0…) of a NIC port; the loopback keeps "lo". */
  linuxIfName(port: string): string;
  /** IPv4 address of a Linux interface. */
  linuxIfIp(name: string): number | undefined;
  /** Sends a packet without passing the output hooks (RST/ICMP generated by the kernel). */
  sendRaw(p: IpPacket): void;
}

export interface KernelLogLine {
  readonly time: number;
  readonly text: string;
}

export class Kernel {
  readonly sysctl: Sysctl;
  readonly netfilter: Netfilter;
  readonly log: KernelLogLine[] = [];
  private readonly host: KernelHost;

  constructor(host: KernelHost) {
    this.host = host;
    this.sysctl = new Sysctl({
      get: () => host.runtimeName(),
      // kernel.hostname is read-only in Netfix: the host name comes from the device name.
      set: () => 'locked',
    });
    this.netfilter = new Netfilter({
      now: () => host.clock.now(),
      log: (line) => this.printk(line),
      ifaceIp: (name) => host.linuxIfIp(name),
      reject: (p, kind, iif) => this.reject(p, kind, iif),
    });
  }

  printk(text: string): void {
    this.log.push({ time: this.host.clock.now(), text });
    if (this.log.length > MAX_KERNEL_LOG) this.log.splice(0, this.log.length - MAX_KERNEL_LOG);
  }

  private name(port: string): string {
    return port === LOOPBACK ? LOOPBACK : this.host.linuxIfName(port);
  }

  prerouting(port: string, p: IpPacket): IpPacket | null {
    return this.netfilter.prerouting(this.name(port), p);
  }

  input(port: string, p: IpPacket): IpPacket | null {
    if (p.icmp?.type === 'echo-request' && this.sysctl.enabled('net.ipv4.icmp_echo_ignore_all')) return null;
    return this.netfilter.input(this.name(port), p);
  }

  output(port: string, p: IpPacket): IpPacket | null {
    return this.netfilter.output(this.name(port), p);
  }

  postrouting(port: string, p: IpPacket, iif?: string): IpPacket | null {
    return this.netfilter.postrouting(this.name(port), p, iif);
  }

  /**
   * `reject`: TCP RST for TCP (unless an ICMP type was asked), ICMP port unreachable otherwise (or the type asked).
   * The RST answers as the destination; the ICMP error comes from this host (the arrival interface when forwarding).
   */
  private reject(p: IpPacket, kind: string | undefined, iif?: string): void {
    if (p.icmp && p.icmp.type !== 'echo-request') return;
    const ttl = LINUX_TTL;
    if (p.tcp && (kind === undefined || kind === 'tcp reset')) {
      this.host.sendRaw({ src: p.dst, dst: p.src, ttl, protocol: 'tcp', tcp: { sport: p.tcp.dport, dport: p.tcp.sport, flags: ['RST', 'ACK'], seq: 0, ack: p.tcp.seq + 1 } });
      return;
    }
    const src = iif === undefined ? p.dst : this.host.linuxIfIp(iif);
    if (src === undefined) return;
    const code: UnreachableCode = kind === 'icmp admin-prohibited' ? 'admin' : kind === 'icmp host-unreachable' ? 'host' : 'port';
    const orig = icmpQuote(p);
    this.host.sendRaw({ src, dst: p.src, ttl, protocol: 'icmp', icmp: { type: 'unreachable', id: p.icmp?.id ?? 0, seq: p.icmp?.seq ?? 0, code, ...(orig ? { orig } : {}) } });
  }
}
